const openApproved = generalPackQuestions.filter((q) => q.editorialStatus === 'approved' && q.openAnswer);

describe('английские алиасы открытых ответов', () => {
  it('у каждой approved open-записи есть acceptedEn или явное исключение с причиной', () => {
    const missing = openApproved
      .filter((q) => !(q.acceptedEn?.length) && !(q.id in NO_EN))
      .map((q) => `${q.id} (${q.answerRu})`);
    expect(missing, 'добавь acceptedEn или внеси id в NO_EN с причиной:\n' + missing.join('\n')).toEqual([]);
  });

  it('список исключений не гниёт', () => {
    const stale = Object.keys(NO_EN).filter((id) => {
      const q = openApproved.find((x) => x.id === id);
      return !q || !!q.acceptedEn?.length;
    });
    expect(stale, 'эти id больше не нужны в NO_EN — убери:\n' + stale.join('\n')).toEqual([]);
  });

  it('английские алиасы не дублируют русские после нормализации', () => {
    for (const q of openApproved) {
      if (!q.acceptedEn) continue;
      const ru = q.acceptedRu.map(normalizePackAnswer);
      const seen: string[] = [];
      for (const en of q.acceptedEn) {
        const n = normalizePackAnswer(en);
        expect(ru.includes(n), `${q.id}: «${en}» дублирует acceptedRu`).toBe(false);
        expect(seen.includes(n), `${q.id}: «${en}» дублирует другой EN-алиас`).toBe(false);
        seen.push(n);
      }
    }
  });
});
