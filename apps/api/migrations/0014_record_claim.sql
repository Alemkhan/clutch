-- Запись достаётся одному сопернику: кто первый забрал, того и матч.
--
-- Раньше запись видели все сразу: десять игроков могли одновременно играть против одной записи,
-- её владелец получал десять уведомлений, а исход записывался от того, кто случайно финишировал
-- первым. Теперь претендент забирает запись атомарным условным UPDATE (аналог SKIP LOCKED,
-- которого в D1 нет): кто изменил строку, тот и забрал.
--
-- claimed_at нужен, чтобы брошенный претендент не запирал чужую запись навсегда: по истечении
-- срока она возвращается в подбор.
--
-- Аддитивно: только новые колонки, существующие строки и индексы не трогаются.
ALTER TABLE match_runs ADD COLUMN claimed_by TEXT;
ALTER TABLE match_runs ADD COLUMN claimed_at INTEGER;

-- Подбор ищет незанятые записи набора; частичный индекс покрывает ровно этот запрос.
CREATE INDEX IF NOT EXISTS idx_match_runs_unclaimed
  ON match_runs(question_set_id, completed_at DESC)
  WHERE claimed_by IS NULL AND reached_target = 1;
