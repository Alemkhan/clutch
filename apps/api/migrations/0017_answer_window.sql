-- Окно ответа, измеренное сервером: от закрытия предыдущего круга (а для первого — от старта
-- забега) до прихода ответа, в миллисекундах.
--
-- Зачем. Время ответа (`response_time_ms`) сообщает клиент, и проверить его сервер не мог ничем.
-- Это окно — верхняя граница: внутрь него входят и разбор, и удар предыдущего круга, поэтому
-- длительностью самого вопроса оно не является. Но заявить время больше окна невозможно, и такой
-- ответ теперь отклоняется; а забеги, где заявленные секунды систематически не похожи на
-- измеренные окна, видно по этой колонке — материал для лиг.
--
-- Чего это не даёт. Настоящий лимит 15 секунд на вопрос так не поставить: весь набор уходит
-- клиенту сразу, поэтому вопрос можно прочитать заранее и «начать» его тогда, когда ответ уже
-- известен. Для лимита набор нужно отдавать по одному вопросу — это отдельное решение с ценой
-- (предзагрузка картинок, возобновление забега после закрытой вкладки).
--
-- Аддитивно: ALTER TABLE ADD COLUMN без пересборки таблицы. NULL — круги до этой миграции.
ALTER TABLE solo_run_rounds ADD COLUMN answer_window_ms REAL;
