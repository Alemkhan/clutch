--
-- Расстояние до цели (`skill_distance`) теперь выводит сервер из этого времени по общей формуле
-- движения маркера, а не принимает готовым числом от устройства. Сырой ввод хранится рядом с
-- выведенным значением: по нему позже можно искать выбросы (невозможно ровные попадания) для
-- матчмейкинга и лиг, не меняя протокол заново.
--
-- Аддитивно: ALTER TABLE ADD COLUMN без пересборки таблицы, индексы и данные не затрагиваются.
-- NULL означает «круг закрыт без удара»: это и старые круги до миграции, и верный ответ,
-- брошенный без удара (сервер закрывает его промахом при возобновлении забега).
